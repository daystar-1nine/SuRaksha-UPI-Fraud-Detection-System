class NaiveLanguageTranslator {
    constructor() {
        this.currentLang = localStorage.getItem("suraksha_lang") || "en";
        this.observer = null;
        // Sort keys by length descending to ensure longer phrases match before shorter sub-words
        this.sortedKeys = Object.keys(hiMap).filter(k => k.length > 2).sort((a, b) => b.length - a.length);
    }

    init() {
        this.setupToggleButton();
        this.applyLanguage(this.currentLang);
        this.setupMutationObserver();
    }

    setupToggleButton() {
        const langBtn = document.getElementById("language-toggle");
        if (!langBtn) return;

        const label = document.getElementById("lang-label");
        if (label) label.innerText = this.currentLang.toUpperCase();

        if (langBtn._hasListener) return;
        langBtn._hasListener = true;

        langBtn.addEventListener("click", () => {
            const icon = langBtn.querySelector(".material-symbols-outlined");
            if (icon) {
                icon.style.transform = "rotate(360deg)";
                icon.style.transition = "transform 0.6s ease";
                setTimeout(() => {
                    icon.style.transform = "none";
                    icon.style.transition = "none";
                }, 600);
            }

            this.toggleLanguage();
        });
    }

    toggleLanguage() {
        this.currentLang = this.currentLang === "en" ? "hi" : "en";
        localStorage.setItem("suraksha_lang", this.currentLang);
        
        const label = document.getElementById("lang-label");
        if (label) label.innerText = this.currentLang.toUpperCase();

        if (this.observer) this.observer.disconnect();

        this.applyLanguage(this.currentLang);

        this.setupMutationObserver();
        
        if (typeof showToast === "function") {
            const msg = this.currentLang === "en" ? "Language switched to English 🇬🇧" : "भाषा बदलकर हिंदी की गई 🇮🇳";
            showToast(msg, "success", 2000);
        }
    }

    applyLanguage(lang) {
        this.translateElement(document.body, lang);
        this.translatePlaceholders(lang);
    }

    escapeRegex(s) {
        return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }

    translateDynamicText(text, lang) {
        if (!text) return text;
        
        let result = text;
        let cleanText = text.replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
        
        if (lang === "hi") {
            // 1. Direct exact match (clean, raw, or trimmed)
            if (hiMap[cleanText]) return hiMap[cleanText];
            if (hiMap[text]) return hiMap[text];
            if (hiMap[text.trim()]) return hiMap[text.trim()];
            
            // 2. Telemetry regexes
            const locRegex = /^Location:\s*(.*)$/i;
            if (locRegex.test(cleanText)) {
                const city = cleanText.match(locRegex)[1].trim();
                const translatedCity = hiMap[city] || city;
                return `स्थान: ${translatedCity}`;
            }
            
            const riskRegex = /^Risk:\s*(\d+%.*)$/i;
            if (riskRegex.test(cleanText)) {
                const val = cleanText.match(riskRegex)[1];
                return `जोखिम: ${val}`;
            }

            const vpaRegex = /^VPA:\s*(.*)$/i;
            if (vpaRegex.test(cleanText)) {
                const addr = cleanText.match(vpaRegex)[1];
                return `वीपीए: ${addr}`;
            }

            // 3. Match keys with length descending
            // Multi-word phrases use split/join; single words use word boundary \b to prevent word corruption
            for (let key of this.sortedKeys) {
                if (/[\s\-\_\:\,\.\?]/.test(key)) {
                    if (result.includes(key)) {
                        result = result.split(key).join(hiMap[key]);
                    }
                } else {
                    const wordRegex = new RegExp('\\b' + this.escapeRegex(key) + '\\b', 'gi');
                    if (wordRegex.test(result)) {
                        result = result.replace(wordRegex, hiMap[key]);
                    }
                }
            }

            // 4. Common word fallbacks
            result = result.replace(/\bBlocked\b/gi, "रोका गया");
            result = result.replace(/\bVerified\b/gi, "सत्यापित");
            result = result.replace(/\bRisk Score\b/gi, "जोखिम स्कोर");
            result = result.replace(/\bConfidence\b/gi, "विश्वास");
        }

        // Auto-decode any literal \uXXXX unicode escape sequences if encountered
        if (typeof result === "string" && result.includes("\\u")) {
            try {
                result = result.replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) => String.fromCharCode(parseInt(hex, 16)));
            } catch (e) {}
        }

        return result;
    }

    translateElement(node, lang) {
        if (node.nodeType === Node.TEXT_NODE) {
            const rawText = node.nodeValue;
            const text = rawText.trim();
            if (!text) return;

            if (node._isTranslating) return;

            if (node._originalText === undefined) {
                node._originalText = text;
            }

            const original = node._originalText;

            if (lang === "hi") {
                const translated = this.translateDynamicText(original, "hi");
                if (text !== translated) {
                    node._isTranslating = true;
                    node.nodeValue = rawText.replace(text, translated);
                    node._isTranslating = false;
                }
            } else {
                if (text !== original) {
                    node._isTranslating = true;
                    node.nodeValue = rawText.replace(text, original);
                    node._isTranslating = false;
                }
            }
        } else {
            if (["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.tagName)) return;
            if (node.classList && node.classList.contains("material-symbols-outlined")) return;
            if (node.id === "language-toggle" || node.id === "lang-label") return;

            for (let child of node.childNodes) {
                this.translateElement(child, lang);
            }
        }
    }

    translatePlaceholders(lang) {
        const inputs = document.querySelectorAll("input, textarea");
        inputs.forEach(input => {
            if (!input.placeholder) return;
            if (input._originalPlaceholder === undefined) {
                input._originalPlaceholder = input.placeholder;
            }
            const original = input._originalPlaceholder;
            if (lang === "hi") {
                if (hiMap[original] && input.placeholder !== hiMap[original]) {
                    input.placeholder = hiMap[original];
                }
            } else {
                if (input.placeholder !== original) {
                    input.placeholder = original;
                }
            }
        });
    }

    setupMutationObserver() {
        if (this.currentLang === "en") return;

        this.observer = new MutationObserver((mutations) => {
            mutations.forEach(mutation => {
                if (mutation.type === "childList") {
                    mutation.addedNodes.forEach(node => {
                        this.translateElement(node, this.currentLang);
                    });
                } else if (mutation.type === "characterData") {
                    this.translateElement(mutation.target, this.currentLang);
                }
            });
        });

        this.observer.observe(document.body, {
            childList: true,
            subtree: true,
            characterData: true
        });
    }
}

if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", () => {
        const translator = new NaiveLanguageTranslator();
        translator.init();
    });
} else {
    const translator = new NaiveLanguageTranslator();
    translator.init();
}
